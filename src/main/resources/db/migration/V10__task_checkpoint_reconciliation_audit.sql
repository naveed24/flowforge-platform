CREATE TABLE task_checkpoint_reconciliation_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    checkpoint_id BIGINT NOT NULL REFERENCES execution_task_checkpoints(id) ON DELETE CASCADE,
    previous_attempt INTEGER NOT NULL,
    previous_claim_token UUID NOT NULL,
    resolved_state VARCHAR(20) NOT NULL,
    evidence_reference VARCHAR(512) NOT NULL,
    reconciled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_task_reconciliation_state CHECK (resolved_state IN ('SUCCEEDED', 'RETRYABLE'))
);
CREATE INDEX idx_task_checkpoint_reconciliation_audit_checkpoint ON task_checkpoint_reconciliation_audit(checkpoint_id, reconciled_at);
